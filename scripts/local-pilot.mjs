#!/usr/bin/env node
// Disposable local pilot for Corner Cup.
//
//   node scripts/local-pilot.mjs start    start the pilot Worker on 127.0.0.1:8788
//   node scripts/local-pilot.mjs stop     stop it (and its workerd child)
//   node scripts/local-pilot.mjs reset    stop it, delete all local pilot data, start again
//   node scripts/local-pilot.mjs status   report the PID, the health probe and the state directory
//
// Everything the pilot writes lives in .local-pilot/ (gitignored): the generated local-only
// credentials, the logs, the PID file and the D1/Miniflare state. No Cloudflare account, staging or
// production database is read or written. Resetting removes only .local-pilot/state.

import { spawn } from "node:child_process";
import crypto from "node:crypto";
import {
  existsSync,
  mkdirSync,
  openSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const PILOT_DIR = path.join(ROOT, ".local-pilot");
const STATE_DIR = path.join(PILOT_DIR, "state");
const LOG_DIR = path.join(PILOT_DIR, "logs");
const ENV_FILE = path.join(PILOT_DIR, "pilot.env");
const PID_FILE = path.join(PILOT_DIR, "pilot.pid");
const CONFIG = path.join(ROOT, "wrangler.pilot.jsonc");
const HOST = "127.0.0.1";
const PORT = 8788;
const BASE_URL = `http://${HOST}:${PORT}`;

function ensureDirs() {
  mkdirSync(PILOT_DIR, { recursive: true });
  mkdirSync(LOG_DIR, { recursive: true });
}

// Fresh, local-only credentials. Nothing here is copied from staging or production, and the values
// are never printed by this script. They are written once and reused, so a restart keeps the same
// owner password and TOTP encryption key.
function ensureEnvFile() {
  if (existsSync(ENV_FILE)) return false;
  ensureDirs();
  const secret = () => crypto.randomBytes(32).toString("base64url");
  const ownerPassword = `pilot-owner-${crypto.randomBytes(9).toString("base64url")}`;
  const lines = [
    "# Generated by scripts/local-pilot.mjs. Local, disposable, never deployed.",
    "# Not production credentials. Delete .local-pilot/ to discard them.",
    `ADMIN_SECRET=${secret()}`,
    `MFA_ENC_KEY=${secret()}`,
    `ORDER_TRACK_SECRET=${secret()}`,
    `OWNER_PASSWORD=${ownerPassword}`,
  ];
  writeFileSync(ENV_FILE, `${lines.join("\n")}\n`, { mode: 0o600 });
  return true;
}

function readPid() {
  try {
    const raw = JSON.parse(readFileSync(PID_FILE, "utf8"));
    return Number.isFinite(Number(raw.pid)) ? Number(raw.pid) : null;
  } catch {
    return null;
  }
}

function isAlive(pid) {
  if (!pid) return false;
  try {
    process.kill(pid, 0);
    return true;
  } catch {
    return false;
  }
}

async function health() {
  try {
    const res = await fetch(`${BASE_URL}/api/health`, { signal: AbortSignal.timeout(2000) });
    const body = await res.text();
    return { ok: res.ok, status: res.status, body: body.slice(0, 120) };
  } catch (error) {
    return { ok: false, status: 0, body: String(error && error.message ? error.message : error) };
  }
}

async function waitForHealth(timeoutMs = 90_000) {
  const started = Date.now();
  while (Date.now() - started < timeoutMs) {
    const probe = await health();
    if (probe.ok) return probe;
    await new Promise((resolve) => setTimeout(resolve, 700));
  }
  return null;
}

async function stop() {
  const pid = readPid();
  if (!pid) {
    console.log("No pilot PID file; nothing recorded to stop.");
    return true;
  }
  if (!isAlive(pid)) {
    rmSync(PID_FILE, { force: true });
    console.log(`Pilot PID ${pid} is already gone.`);
    return true;
  }

  // Kill the recorded process tree only. A pattern kill could match this agent's own command line,
  // so the PID from our own file is the only handle used.
  if (process.platform === "win32") {
    const result = spawn("taskkill", ["/PID", String(pid), "/T", "/F"], { stdio: "ignore" });
    result.on("error", () => {});
  } else {
    try {
      process.kill(-pid, "SIGTERM");
    } catch {
      try {
        process.kill(pid, "SIGTERM");
      } catch {}
    }
  }

  const deadline = Date.now() + 15_000;
  while (Date.now() < deadline) {
    if (!isAlive(pid)) break;
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  rmSync(PID_FILE, { force: true });
  console.log(isAlive(pid) ? `Pilot PID ${pid} is still shutting down.` : `Pilot stopped (PID ${pid}).`);
  return !isAlive(pid);
}

async function start() {
  ensureDirs();
  const created = ensureEnvFile();
  if (created) console.log(`Generated local-only credentials in ${path.relative(ROOT, ENV_FILE)}.`);

  if (!existsSync(path.join(ROOT, "dist", "index.html"))) {
    console.error("dist/index.html is missing. Run `npm run build` first.");
    process.exitCode = 1;
    return;
  }

  const existingPid = readPid();
  if (isAlive(existingPid)) {
    const probe = await health();
    if (probe.ok) {
      console.log(`Pilot already running at ${BASE_URL} (PID ${existingPid}).`);
      return;
    }
    console.log(`PID ${existingPid} is alive but not answering; restarting it.`);
    stop();
  }

  const out = openSync(path.join(LOG_DIR, "worker.log"), "a");
  const err = openSync(path.join(LOG_DIR, "worker.err.log"), "a");
  const args = [
    "wrangler",
    "dev",
    "--config",
    CONFIG,
    "--ip",
    HOST,
    "--port",
    String(PORT),
    "--persist-to",
    STATE_DIR,
    "--env-file",
    ENV_FILE,
  ];

  const child = spawn(process.platform === "win32" ? "npx.cmd" : "npx", args, {
    cwd: ROOT,
    detached: true,
    stdio: ["ignore", out, err],
    shell: process.platform === "win32",
    windowsHide: true,
  });
  child.unref();
  writeFileSync(
    PID_FILE,
    `${JSON.stringify({ pid: child.pid, port: PORT, startedAt: new Date().toISOString() }, null, 2)}\n`
  );

  console.log(`Starting pilot Worker (PID ${child.pid}); waiting for /api/health...`);
  const probe = await waitForHealth();
  if (!probe) {
    console.error("The pilot did not answer /api/health within 90 s. See .local-pilot/logs/worker.log.");
    process.exitCode = 1;
    return;
  }
  console.log(`Pilot ready at ${BASE_URL} — café /c/corner-cup-local-pilot`);
  console.log(`State: ${path.relative(ROOT, STATE_DIR)}  Logs: .local-pilot/logs/`);
}

async function reset() {
  await stop();
  ensureDirs();
  const stateExisted = existsSync(STATE_DIR);
  // Windows releases the D1/workerd file handles a moment after the process tree is killed, so the
  // delete is retried rather than reported as a failure on the first EPERM/EBUSY.
  try {
    rmSync(STATE_DIR, { recursive: true, force: true, maxRetries: 20, retryDelay: 250 });
  } catch (error) {
    console.error(`Could not delete .local-pilot/state: ${error && error.code ? error.code : error}`);
  }
  if (existsSync(STATE_DIR)) {
    console.error("Could not remove .local-pilot/state; stop any process holding it and retry.");
    process.exitCode = 1;
    return;
  }
  console.log(
    stateExisted
      ? "Deleted .local-pilot/state (disposable D1 and Miniflare data). The owner password and MFA key are kept."
      : "No local pilot state existed; nothing to delete."
  );
  await start();
}

async function status() {
  const pid = readPid();
  const probe = await health();
  console.log(`PID:    ${pid || "(none recorded)"}${pid && isAlive(pid) ? " (alive)" : " (not running)"}`);
  console.log(`Health: ${probe.ok ? "ok" : "down"} (${probe.status}) ${probe.ok ? "" : probe.body}`.trim());
  console.log(`URL:    ${BASE_URL}`);
  console.log(`State:  ${path.relative(ROOT, STATE_DIR)}${existsSync(STATE_DIR) ? "" : " (not created yet)"}`);
  console.log(`Config: ${path.relative(ROOT, CONFIG)}`);
}

const command = String(process.argv[2] || "status").toLowerCase();
if (command === "start") await start();
else if (command === "stop") await stop();
else if (command === "reset") await reset();
else if (command === "status") await status();
else {
  console.error("Usage: node scripts/local-pilot.mjs <start|stop|reset|status>");
  process.exitCode = 2;
}
