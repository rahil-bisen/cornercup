// F-07 phase 2B. PKCE material and the encrypted sign-in state record.
//
// The verifier is the one secret that must survive a round trip through the browser, and it must not
// be readable in the database or in a backup. It is therefore never stored in plaintext: the row
// holds AES-256-GCM output under a key derived from a dedicated secret with HKDF-SHA256. There is no
// digest-only fallback, because a digest would still let an attacker who reads the table complete
// the exchange.
//
// If the key is missing or too weak, every helper throws. Callers turn that into 503 rather than
// silently degrading to a weaker scheme.

const HKDF_SALT = "corner-cup";
const HKDF_INFO = "owner-signin-state:v1";
const IV_BYTES = 12;
const MIN_KEY_LENGTH = 32;

function base64url(bytes) {
  let binary = "";
  for (const byte of bytes) binary += String.fromCharCode(byte);
  return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

function fromBase64(text) {
  const normalised = String(text).replace(/-/g, "+").replace(/_/g, "/");
  const padded = normalised + "=".repeat((4 - (normalised.length % 4)) % 4);
  const binary = atob(padded);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i += 1) bytes[i] = binary.charCodeAt(i);
  return bytes;
}

export function randomToken(bytes = 32) {
  return base64url(crypto.getRandomValues(new Uint8Array(bytes)));
}

// PKCE S256. The verifier is 32 random bytes; the challenge is the base64url SHA-256 of its ASCII
// encoding, which is exactly what the provider expects.
export async function newPkce() {
  const verifier = randomToken(32);
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(verifier));
  return { verifier, challenge: base64url(new Uint8Array(digest)) };
}

export async function sha256Hex(message) {
  const digest = await crypto.subtle.digest("SHA-256", new TextEncoder().encode(String(message)));
  let out = "";
  for (const byte of new Uint8Array(digest)) out += byte.toString(16).padStart(2, "0");
  return out;
}

let cachedKey = null;
let cachedSecret = null;

async function stateKey(env) {
  const secret = env && env.WORKOS_STATE_ENCRYPTION_KEY;
  if (typeof secret !== "string" || secret.length < MIN_KEY_LENGTH) {
    throw new Error("WORKOS_STATE_ENCRYPTION_KEY is missing or too short");
  }
  if (cachedKey && cachedSecret === secret) return cachedKey;

  const material = await crypto.subtle.importKey("raw", new TextEncoder().encode(secret), "HKDF", false, [
    "deriveKey",
  ]);
  const key = await crypto.subtle.deriveKey(
    {
      name: "HKDF",
      hash: "SHA-256",
      salt: new TextEncoder().encode(HKDF_SALT),
      info: new TextEncoder().encode(HKDF_INFO),
    },
    material,
    { name: "AES-GCM", length: 256 },
    false,
    ["encrypt", "decrypt"]
  );
  cachedKey = key;
  cachedSecret = secret;
  return key;
}

// Returns base64(iv || ciphertext || tag). A fresh IV per call is generated by the platform CSPRNG;
// reusing one under the same key would break GCM's guarantees.
export async function encryptState(env, value) {
  const key = await stateKey(env);
  const iv = crypto.getRandomValues(new Uint8Array(IV_BYTES));
  const ciphertext = await crypto.subtle.encrypt(
    { name: "AES-GCM", iv },
    key,
    new TextEncoder().encode(String(value))
  );
  const combined = new Uint8Array(iv.length + ciphertext.byteLength);
  combined.set(iv, 0);
  combined.set(new Uint8Array(ciphertext), iv.length);
  return base64url(combined);
}

// Returns null for anything that does not authenticate: a wrong key, a truncated value, a tampered
// tag. The caller treats null as "this sign-in cannot continue".
export async function decryptState(env, encoded) {
  try {
    const key = await stateKey(env);
    const combined = fromBase64(String(encoded || ""));
    if (combined.length <= IV_BYTES) return null;
    const iv = combined.slice(0, IV_BYTES);
    const body = combined.slice(IV_BYTES);
    const plaintext = await crypto.subtle.decrypt({ name: "AES-GCM", iv }, key, body);
    return new TextDecoder().decode(plaintext);
  } catch {
    return null;
  }
}

// Ties a claim to the sign-in that presented it without putting the claim code in the URL twice: the
// state row stores only this digest.
export async function claimDigest(code) {
  return sha256Hex(`claim:${String(code || "")}`);
}
